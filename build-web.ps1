# Build the phone version (PWA) into web\ : a static folder for any https hosting (GitHub Pages, Netlify, ...).
# Run:  powershell -ExecutionPolicy Bypass -File build-web.ps1
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$out = Join-Path $root 'web'
$utf8 = New-Object System.Text.UTF8Encoding $false
if (Test-Path $out) { Remove-Item -Recurse -Force $out }
New-Item -ItemType Directory -Force $out | Out-Null

# page: index-gl.html becomes index.html; links to the desktop-only views are dropped
$html = [IO.File]::ReadAllText((Join-Path $root 'index-gl.html'), $utf8)
$html = [regex]::Replace($html, '\s*<a class="viewlink"[^>]*>[^<]*</a>', '')
[IO.File]::WriteAllText((Join-Path $out 'index.html'), $html, $utf8)

$copy = @('manifest.webmanifest', 'css\style.css', 'css\style3d.css', 'css\gl.css', 'css\hud.css', 'css\mobile.css') +
  (Get-ChildItem "$root\js" -Recurse -Filter *.js | Where-Object { $_.Name -ne 'camera3d.js' } | ForEach-Object { $_.FullName.Substring($root.Length + 1) }) +
  (Get-ChildItem "$root\models" -Recurse -Filter *.glb | ForEach-Object { $_.FullName.Substring($root.Length + 1) }) +
  (Get-ChildItem "$root\icons" -Filter *.png | ForEach-Object { $_.FullName.Substring($root.Length + 1) })
foreach ($f in $copy) {
  $dst = Join-Path $out $f
  New-Item -ItemType Directory -Force (Split-Path $dst) | Out-Null
  Copy-Item (Join-Path $root $f) $dst
}
New-Item -ItemType File (Join-Path $out '.nojekyll') | Out-Null

# service worker: precache every file; the cache name changes whenever any file changes
$files = @('index.html') + ($copy | ForEach-Object { $_ -replace '\\', '/' })
$sha = [Security.Cryptography.SHA256]::Create()
$ms = New-Object IO.MemoryStream
foreach ($f in $files) { $b = [IO.File]::ReadAllBytes((Join-Path $out $f)); $ms.Write($b, 0, $b.Length) }
$ver = ([BitConverter]::ToString($sha.ComputeHash($ms.ToArray())) -replace '-', '').Substring(0, 12).ToLower()
$list = ($files | ForEach-Object { "  './$_'" }) -join ",`n"
$sw = @"
// Fraction Chess - offline cache (generated by build-web.ps1)
const CACHE = 'fc-$ver';
const FILES = [
$list
];
self.addEventListener('install', e => {
  // cache: 'reload' - always take fresh files from the server, not stale copies from the browser HTTP cache
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES.map(f => new Request(f, { cache: 'reload' })))).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET') return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then(hit => hit ||
    (e.request.mode === 'navigate' ? caches.match('./index.html') : null)).then(hit => hit || fetch(e.request)));
});
"@
[IO.File]::WriteAllText((Join-Path $out 'sw.js'), $sw, $utf8)

$size = (Get-ChildItem $out -Recurse -File | Measure-Object Length -Sum).Sum
Write-Host ("OK: $out  ({0} files, {1:N1} MB, cache fc-$ver)" -f ($files.Count + 2), ($size / 1MB))
